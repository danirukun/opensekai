import { expect, it, vi } from "vitest";
import { makeSmokeScene, type PublisherClient, type ConnectionDescriptor } from "@opensekai/contracts";
import { createWorkerHost } from "../src/worker";
const descriptor: ConnectionDescriptor = { schemaVersion: 1, sessionId: "test", httpOrigin: "http://127.0.0.1:1234", wsUrl: "ws://127.0.0.1:1234/ws", role: "publisher", token: "test", capabilities: ["read", "edit"], outputId: null };
it("owns one timer, routes calls, stops and restarts cleanly", async () => {
    let now = 100, callback = () => { };
    const close = vi.fn(), remove = vi.fn(), publishFrame = vi.fn();
    let listener: Parameters<PublisherClient["onCall"]>[0];
    const client: PublisherClient = { close, publishFrame, onCall: fn => { listener = fn; return remove; } };
    const start = vi.fn((fn: () => void, ms: number) => { expect(ms).toBe(1000 / 60); callback = fn; return 7; }), clear = vi.fn();
    const host = createWorkerHost({ connect: async () => client, now: () => now, setInterval: start, clearInterval: clear });
    const initial = { descriptor, scene: makeSmokeScene() };
    await host.handle(initial);
    await host.handle(initial);
    expect(start).toHaveBeenCalledTimes(1);
    now = 1100;
    callback();
    expect(publishFrame.mock.calls[0]![0]).toMatchObject({ tick: 60, sequence: 1 });
    expect(await listener!({ requestId: "q", method: "sceneInspect", params: { sceneId: "scene_smoke" } })).toMatchObject({ ok: true });
    expect(await listener!({ requestId: "q", method: "sceneInspect", params: { sceneId: "wrong" } })).toMatchObject({ ok: false, error: { code: "NOT_FOUND" } });
    await host.handle({ kind: "stop" });
    callback();
    expect(publishFrame).toHaveBeenCalledTimes(1);
    expect(close).toHaveBeenCalledTimes(1);
    expect(remove).toHaveBeenCalledTimes(1);
    expect(clear).toHaveBeenCalledWith(7);
    await host.handle(initial);
    expect(start).toHaveBeenCalledTimes(2);
    await host.handle({ kind: "stop" });
});
it("closes a connection that resolves after stop without starting a timer", async () => {
    let resolve!: (c: PublisherClient) => void;
    const close = vi.fn(), start = vi.fn();
    const host = createWorkerHost({ connect: () => new Promise(r => resolve = r), now: () => 0, setInterval: start, clearInterval: vi.fn() });
    const pending = host.handle({ descriptor, scene: makeSmokeScene() });
    await host.handle({ kind: "stop" });
    resolve({ close, onCall: vi.fn(), publishFrame: vi.fn() });
    await pending;
    expect(close).toHaveBeenCalledOnce();
    expect(start).not.toHaveBeenCalled();
});
it("releases publisher resources if timer startup fails and permits retry", async () => {
    const close = vi.fn(), remove = vi.fn();
    const client: PublisherClient = { close, onCall: () => remove, publishFrame: vi.fn() };
    const start = vi.fn().mockImplementationOnce(() => { throw new Error("timer unavailable"); }).mockReturnValue(1);
    const host = createWorkerHost({ connect: async () => client, now: () => 0, setInterval: start, clearInterval: vi.fn() });
    await expect(host.handle({ descriptor, scene: makeSmokeScene() })).rejects.toThrow("timer unavailable");
    expect(close).toHaveBeenCalledOnce();
    expect(remove).toHaveBeenCalledOnce();
    await host.handle({ descriptor, scene: makeSmokeScene() });
    expect(start).toHaveBeenCalledTimes(2);
    await host.handle({ kind: "stop" });
});
